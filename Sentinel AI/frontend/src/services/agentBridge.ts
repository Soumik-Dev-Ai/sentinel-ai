/**
 * AgentBridge — connects the React UI to the real Python agent backend.
 *
 * Uses simulated data as fallback when the Python API is unavailable.
 * Configure AGENT_API_URL in .env to point to your running agent server.
 */

import { TERMINAL_LINES, CODE_LINES } from "../data/simulatedData";

const AGENT_API_URL = import.meta.env.VITE_AGENT_API_URL || "http://localhost:9000";

export interface AgentResult {
  success: boolean;
  goal: string;
  steps_taken: number;
  self_corrections: number;
  final_output: string | null;
  errors: string[];
  terminal_logs: string[];
  generated_code: Record<string, string>;
  metrics: {
    steps: number;
    self_corrections: number;
    provider_switches: number;
    unresolvable_count: number;
    elapsed_seconds: number;
    budget_remaining: number;
  };
}

export interface TerminalLine {
  text: string;
  type: "command" | "info" | "step" | "action" | "success" | "error"
    | "recovery" | "done" | "complete" | "separator";
  delay: number;
}

export interface CodeLine {
  text: string;
  type: "comment" | "code" | "error" | "recovery" | "fix" | "success" | "blank";
  delay: number;
}

function parseTerminalLines(logs: string[]): TerminalLine[] {
  return logs.map((line, i) => {
    let type: TerminalLine["type"] = "info";
    const lower = line.toLowerCase();
    if (lower.includes("[step")) type = "step";
    else if (
      (lower.includes("action"))
    ) type = "action";
    else if (
      lower.includes("[eval]") &&
      (lower.includes("success=true") || lower.includes("✓"))
    )
      type = "success";
    else if (
      lower.includes("[eval]") &&
      (lower.includes("mode=f") || lower.includes("✗"))
    )
      type = "error";
    else if (
      lower.includes("[recovery") ||
      lower.includes("recovery")
    )
      type = "recovery";
    else if (
      lower.includes("[ok]") ||
      lower.includes("[complete")
    )
      type = "done";
    else if (lower.startsWith("$ ") || lower.startsWith("sentinel"))
      type = "command";
    else if (
      lower.includes("──") ||
      lower.includes("===") ||
      lower.includes("━")
    )
      type = "separator";
    else if (lower.includes("result:") || lower.includes("finished"))
      type = "complete";
    return { text: line, type, delay: 200 + i * 300 };
  });
}

function parseCodeLines(generatedCode: Record<string, string>): CodeLine[] {
  const lines: CodeLine[] = [];
  for (const [path, content] of Object.entries(generatedCode)) {
    lines.push({
      text: `# ${path} — Generated by Sentinel AI`,
      type: "comment",
      delay: 0,
    });
    for (const rawLine of content.split("\n")) {
      const trimmed = rawLine.trim();
      if (trimmed === "") {
        lines.push({ text: "", type: "blank", delay: 0 });
      } else if (trimmed.startsWith("#") || trimmed.startsWith('"""')) {
        lines.push({ text: rawLine, type: "comment", delay: 0 });
      } else {
        lines.push({ text: rawLine, type: "code", delay: 0 });
      }
    }
    lines.push({ text: "", type: "blank", delay: 0 });
  }
  return lines;
}

function finalOutputFromResult(result: AgentResult): string {
  let out = result.final_output || "";
  if (!out) {
    out = "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━";
    out += `\n  SENTINEL AI — Agent Run Complete`;
    out += `\n\n  Goal:  ${result.goal || "—"}`;
    out += `\n\n  Steps: ${result.steps_taken}  |  Self-Corrections: ${result.self_corrections}`;
    out += `\n  Provider Switches: ${result.metrics.provider_switches}`;
  }
  if (result.generated_code && Object.keys(result.generated_code).length > 0) {
    if (out && !out.endsWith("\n")) out += "\n";
    out += "\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━";
    out += "\n  Generated Code (Raw)";
    out += "\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━";
    for (const [filename, content] of Object.entries(result.generated_code)) {
      out += `\n\n  📄 ${filename}`;
      out += `\n  ${"─".repeat(48)}`;
      out += `\n${content}\n`;
    }
  }
  out += "\n  Status: COMPLETE ✓";
  return out;
}

/**
 * Call the real Python agent API. Falls back to simulation on failure.
 */
export async function runRealAgent(
  goal: string,
  inputText?: string,
  apiUrl?: string
): Promise<AgentResult> {
  const url = apiUrl || AGENT_API_URL;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 120000);

  try {
    const response = await fetch(`${url}/api/run-agent`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ goal, input: inputText || "" }),
      signal: controller.signal,
    });

    clearTimeout(timeout);

    if (response.ok) {
      const result = (await response.json()) as AgentResult;
      return result;
    }

    throw new Error(`API returned ${response.status}`);
  } catch (err) {
    clearTimeout(timeout);
    console.warn(
      `Agent API at ${url} unavailable, using simulation:`,
      err instanceof Error ? err.message : err
    );
    return getSimulatedResult(goal);
  }
}

/**
 * Returns simulated agent data for demo/fallback mode.
 */
export function getSimulatedResult(goal: string): AgentResult {
  return {
    success: true,
    goal,
    steps_taken: 6,
    self_corrections: 1,
    final_output: null,
    errors: [],
    terminal_logs: TERMINAL_LINES.map((l) => l.text),
    generated_code: {
      "main.py": `def fibonacci(n: int) -> int:
    """Return the nth Fibonacci number using O(1) space."""
    if n <= 1:
        return n
    a, b = 0, 1
    for _ in range(2, n + 1):
        a, b = b, a + b
    return b`,
      "tests/test_main.py": `import pytest
from main import fibonacci

def test_base_cases():
    assert fibonacci(0) == 0
    assert fibonacci(1) == 1

def test_fibonacci_sequence():
    assert fibonacci(6) == 8

def test_larger_values():
    assert fibonacci(10) == 55
    assert fibonacci(20) == 6765`,
    },
    metrics: {
      steps: 6,
      self_corrections: 1,
      provider_switches: 0,
      unresolvable_count: 0,
      elapsed_seconds: 1.2,
      budget_remaining: 2,
    },
  };
}

/**
 * Parse an AgentResult into terminal/code display lines for the UI.
 */
export function agentResultToDisplay(result: AgentResult) {
  const terminalLines = parseTerminalLines(result.terminal_logs);
  const codeLines = parseCodeLines(result.generated_code);
  const finalOutput = finalOutputFromResult(result);
  return { terminalLines, codeLines, finalOutput };
}